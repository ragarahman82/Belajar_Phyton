#Dengan input(), pengguna bisa memasukkan data ketika program sedang berjalan.
nama = input("Masukkan nama Anda: ")
umur = int(input("Masukkan umur Anda: "))   
jurusan = input("Masukkan jurusan Anda: ")

print("Nama:", nama)
print("Umur:", umur)
print("Jurusan:", jurusan)


angka_pertama = int(input("Masukkan angka pertama: "))
angka_kedua = int(input("Masukkan angka kedua: "))
penjumlahan = angka_pertama + angka_kedua
pengurangan = angka_pertama - angka_kedua
perkalian = angka_pertama * angka_kedua

print("Hasil penjumlahan:", penjumlahan)
print("Hasil pengurangan:", pengurangan)
print("Hasil perkalian:", perkalian)

    

