# Variable in Python (Variable di phyton juga salah satu kondep paling penting dalam pemrograman, karena variabel digunakan untuk menyimpan data yang dapat digunakan kembali di dalam program.)
nama = "Raga"  # String variable
umur = 25  # Integer variable
tinggi = 175.5  # Float variable
jurusan = "Informatika"  # String variable

print(nama)  # Output: Raga
print(umur)  # Output: 25   
print(tinggi)  # Output: 175.5
print(jurusan)  # Output: Informatika

# Variable juga bisa menyimpan angka dan bisa juga dihitung, contohnya seperti ini:
umur = 30  # Mengubah nilai variabel umur menjadi 30
print(umur + 1)  # Output: 31

# Variable bisa menyimpan hasil perhitungan, contohnya seperti ini:
a = 10
b = 20

hasil = a + b

print(hasil)

